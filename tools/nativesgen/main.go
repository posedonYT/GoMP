// Command nativesgen generates typed C++ wrappers for the GTA V natives that
// the game client actually uses. It scans the client sources for
// NAMESPACE::NATIVE_NAME( calls and looks them up in alloc8or's
// gta5-nativedb-data natives.json, so the header stays small and every name
// is checked against the database at generation time.
//
//	go run ./tools/nativesgen -db natives.json -src client/game -out client/game/natives.hpp
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type param struct {
	Type string `json:"type"`
	Name string `json:"name"`
}

type native struct {
	Name       string  `json:"name"`
	Params     []param `json:"params"`
	ReturnType string  `json:"return_type"`
	Build      string  `json:"build"`
}

var callRe = regexp.MustCompile(`\b([A-Z][A-Z0-9_]*)::([A-Z_][A-Z0-9_]*)\s*\(`)

var cppKeywords = map[string]bool{
	"default": true, "register": true, "new": true, "delete": true, "class": true, "struct": true,
	"template": true, "this": true, "char": true, "int": true, "float": true, "bool": true, "auto": true,
	"switch": true, "case": true, "public": true, "private": true, "protected": true, "operator": true,
	"union": true, "enum": true, "unsigned": true, "signed": true, "long": true, "short": true, "double": true,
	"const": true, "volatile": true, "static": true, "extern": true, "friend": true, "virtual": true,
	"inline": true, "return": true, "if": true, "else": true, "for": true, "while": true, "do": true,
	"break": true, "continue": true, "goto": true, "try": true, "catch": true, "throw": true, "using": true,
	"namespace": true, "typedef": true, "sizeof": true, "export": true, "module": true, "near": true, "far": true,
}

func main() {
	db := flag.String("db", "natives.json", "path to natives.json from alloc8or/gta5-nativedb-data")
	src := flag.String("src", "client/game", "directory with client sources to scan")
	out := flag.String("out", "client/game/natives.hpp", "output header")
	flag.Parse()
	if err := run(*db, *src, *out); err != nil {
		fmt.Fprintln(os.Stderr, "nativesgen:", err)
		os.Exit(1)
	}
}

func run(dbPath, src, out string) error {
	raw, err := os.ReadFile(dbPath)
	if err != nil {
		return err
	}
	var db map[string]map[string]native
	if err := json.Unmarshal(raw, &db); err != nil {
		return fmt.Errorf("%s: %w", dbPath, err)
	}
	type key struct{ ns, name string }
	index := map[key]string{} // -> hash
	for ns, fns := range db {
		for hash, n := range fns {
			index[key{ns, n.Name}] = hash
		}
	}
	used := map[key]bool{}
	outAbs, _ := filepath.Abs(out)
	err = filepath.WalkDir(src, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		if ext := filepath.Ext(p); ext != ".cpp" && ext != ".hpp" && ext != ".h" {
			return nil
		}
		if abs, _ := filepath.Abs(p); abs == outAbs {
			return nil
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		for _, m := range callRe.FindAllStringSubmatch(string(data), -1) {
			if _, ok := db[m[1]]; ok {
				used[key{m[1], m[2]}] = true
			}
		}
		return nil
	})
	if err != nil {
		return err
	}
	var missing []string
	byNS := map[string][]key{}
	for k := range used {
		if _, ok := index[k]; !ok {
			missing = append(missing, k.ns+"::"+k.name)
			continue
		}
		byNS[k.ns] = append(byNS[k.ns], k)
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return fmt.Errorf("natives not found in the database: %s", strings.Join(missing, ", "))
	}
	namespaces := make([]string, 0, len(byNS))
	for ns := range byNS {
		namespaces = append(namespaces, ns)
	}
	sort.Strings(namespaces)

	var b strings.Builder
	b.WriteString("// Code generated by tools/nativesgen from alloc8or/gta5-nativedb-data. DO NOT EDIT.\n")
	b.WriteString("// Regenerate after using a new native: go run ./tools/nativesgen -db natives.json\n")
	b.WriteString("#pragma once\n\n#include \"shv.hpp\"\n")
	count := 0
	for _, ns := range namespaces {
		keys := byNS[ns]
		sort.Slice(keys, func(i, j int) bool { return keys[i].name < keys[j].name })
		fmt.Fprintf(&b, "\nnamespace %s {\n", ns)
		for _, k := range keys {
			hash := index[k]
			n := db[ns][hash]
			ret := cppType(n.ReturnType)
			var params, args []string
			taken := map[string]bool{}
			for i, p := range n.Params {
				name := p.Name
				if name == "" || cppKeywords[name] {
					name = fmt.Sprintf("%s_%d", name, i)
				}
				for taken[name] {
					name = fmt.Sprintf("%s_%d", name, i)
				}
				taken[name] = true
				params = append(params, cppType(p.Type)+" "+name)
				args = append(args, name)
			}
			call := hash + "ull"
			if len(args) > 0 {
				call += ", " + strings.Join(args, ", ")
			}
			fmt.Fprintf(&b, "inline %s %s(%s) { return invoke<%s>(%s); }\n", ret, n.Name, strings.Join(params, ", "), ret, call)
			count++
		}
		fmt.Fprintf(&b, "}  // namespace %s\n", ns)
	}
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("generated %d natives into %s\n", count, out)
	return nil
}

func cppType(t string) string {
	switch t {
	case "Any", "Hash", "Ped", "Vehicle", "Entity", "Player", "Object", "Blip", "Cam", "Pickup", "Interior",
		"ScrHandle", "FireId", "BOOL", "int", "float", "void", "Vector3", "const char*", "char*",
		"Any*", "int*", "float*", "Vector3*", "BOOL*", "Hash*", "Entity*", "Vehicle*", "Ped*", "Object*", "Blip*", "ScrHandle*":
		return t
	}
	return "Any"
}
